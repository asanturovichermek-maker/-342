// Перемешивание массива
function shuffle(array) {
  const result = [...array];

  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }

  return result;
}

function stopTimer() {
  if (timerId !== null) {
    clearInterval(timerId);
    timerId = null;
  }
}

function startGame() {
  stopTimer();

  const selectedCategory = categorySelect.value;

  gameQuestions = questions.filter(question =>
    selectedCategory === "all" ||
    question[0] === selectedCategory
  );

  if (gameQuestions.length === 0) {
    alert("В этой категории пока нет вопросов.");
    return;
  }

  gameQuestions = shuffle(gameQuestions);
  currentIndex = 0;
  score = 0;
  correctAnswers = 0;

  startScreen.classList.add("hidden");
  resultScreen.classList.add("hidden");
  quizScreen.classList.remove("hidden");

  showQuestion();
}

function showQuestion() {
  stopTimer();
  answered = false;
  timeLeft = 20;

  const q = gameQuestions[currentIndex];

  questionCounter.textContent =
    `Вопрос ${currentIndex + 1} из ${gameQuestions.length}`;

  scoreElement.textContent = `⭐ ${score}`;
  questionCategory.textContent = q[0];
  questionText.textContent = q[1];

  progress.style.width =
    `${(currentIndex / gameQuestions.length) * 100}%`;

  feedback.textContent = "";
  feedback.className = "feedback";
  nextButton.classList.add("hidden");

  answersElement.replaceChildren();

  q[2].forEach((answer, index) => {
    const button = document.createElement("button");

    button.type = "button";
    button.className = "answer-btn";
    button.textContent =
      `${String.fromCharCode(65 + index)}. ${answer}`;

    button.addEventListener("click", () => selectAnswer(index));

    answersElement.appendChild(button);
  });

  updateTimer();

  timerId = setInterval(() => {
    timeLeft--;
    updateTimer();

    if (timeLeft <= 0) {
      stopTimer();
      selectAnswer(-1);
    }
  }, 1000);
}

function updateTimer() {
  timerElement.textContent = `⏱ ${timeLeft}`;

  if (timeLeft <= 5) {
    timerElement.style.color = "#fda4af";
  } else {
    timerElement.style.color = "#ffffff";
  }
}

function selectAnswer(selectedIndex) {
  if (answered) return;

  answered = true;
  stopTimer();

  const q = gameQuestions[currentIndex];
  const correctIndex = q[3];
  const buttons = answersElement.querySelectorAll("button");

  buttons.forEach((button, index) => {
    button.disabled = true;

    if (index === correctIndex) {
      button.classList.add("correct");
    }

    if (index === selectedIndex && index !== correctIndex) {
      button.classList.add("wrong");
    }
  });

  if (selectedIndex === correctIndex) {
    correctAnswers++;

    // 10 очков за ответ и бонус за скорость.
    const bonus = Math.floor(timeLeft / 5);
    score += 10 + bonus;

    feedback.textContent =
      `✅ Правильно! +${10 + bonus} очков. Отличная работа!`;

    feedback.classList.add("good");
  } else if (selectedIndex === -1) {
    feedback.textContent =
      `⏰ Время вышло! Правильный ответ: ${q[2][correctIndex]}`;

    feedback.classList.add("bad");
  } else {
    feedback.textContent =
      `❌ Неверно. Правильный ответ: ${q[2][correctIndex]}`;

    feedback.classList.add("bad");
  }

  scoreElement.textContent = `⭐ ${score}`;

  progress.style.width =
    `${((currentIndex + 1) / gameQuestions.length) * 100}%`;

  nextButton.textContent =
    currentIndex === gameQuestions.length - 1
      ? "Посмотреть результат 🏆"
      : "Следующий вопрос →";

  nextButton.classList.remove("hidden");
}

function nextQuestion() {
  if (!answered) return;

  currentIndex++;

  if (currentIndex >= gameQuestions.length) {
    finishGame();
  } else {
    showQuestion();
  }
}

function finishGame() {
  stopTimer();

  quizScreen.classList.add("hidden");
  resultScreen.classList.remove("hidden");

  const total = gameQuestions.length;
  const percent = Math.round((correctAnswers / total) * 100);

  document.getElementById("finalScore").textContent = score;
  document.getElementById("correctCount").textContent =
    `${correctAnswers}/${total}`;

  document.getElementById("percent").textContent = `${percent}%`;

  let message;

  if (percent >= 90) {
    message = "🌟 Великолепно! Ты настоящий эрудит!";
  } else if (percent >= 70) {
    message = "🎉 Отличный результат! Ты много знаешь!";
  } else if (percent >= 50) {
    message = "👏 Хорошая работа! Продолжай узнавать новое.";
  } else {
    message = "💪 Не сдавайся! Каждая игра помогает учиться.";
  }

  document.getElementById("resultMessage").textContent = message;
}

function goHome() {
  stopTimer();
  quizScreen.classList.add("hidden");
  resultScreen.classList.add("hidden");
  startScreen.classList.remove("hidden");
}

// Подключаем кнопки
startButton.addEventListener("click", startGame);
nextButton.addEventListener("click", nextQuestion);
restartButton.addEventListener("click", startGame);
homeButton.addEventListener("click", goHome);

